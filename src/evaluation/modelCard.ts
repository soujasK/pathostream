/**
 * Renders MODEL_CARD.md. Structure follows Mitchell et al., "Model Cards for
 * Model Reporting" (FAT* 2019): model details, intended use, factors,
 * metrics, evaluation data, training data, quantitative analyses, ethical
 * considerations, caveats and recommendations. The appendix is a short
 * datasheet for the synthetic telemetry, after Gebru et al., "Datasheets for
 * Datasets" (Communications of the ACM 64(12):86-92, 2021).
 *
 * Headline numbers are interpolated from the committed evaluation results so
 * the card cannot drift from EVALUATION.md.
 */

import { ASSUMED_SAMPLING_MINUTES, type EvaluationResults } from "./experiments.js";

const int = (x: number) => Math.round(x).toLocaleString("en-US");
const one = (x: number) => x.toFixed(1);

export function renderModelCard(r: EvaluationResults): string {
  const k = r.design.escalationThresholdTicks;
  const shipped = r.persistence.find((p) => p.k === k)!;
  const at = (shift: number) => r.delay.rows.find((row) => row.shift === shift)!;
  const scenario = (prefix: string) => r.robustness.find((x) => x.scenario.startsWith(prefix))!;
  const stationsText = `${r.networkStations} stations`;

  return `# Model card

Format after Mitchell et al., *Model Cards for Model Reporting* (FAT* 2019). Generated by \`npm run evaluate\` (do not edit by hand); numbers come from \`evaluation/results.json\`. Companion documents: [EVALUATION.md](EVALUATION.md) (evidence), [SAFETY_CASE.md](SAFETY_CASE.md) (hazards and regulation), [METHODS.md](METHODS.md) (sources and derivations).

> **This is a research prototype on synthetic data. It is not a medical device and has not been validated on any real river, sensor or patient.**

## Model details

There is **no learned model**. The system is three fixed-rule components:

| Component | What it is | Parameters |
| --- | --- | --- |
| Early-warning detector | Two-sided EWMA control chart (Roberts 1959, *Technometrics* 1(3):239-250) with exact time-varying limits, followed by an escalation rule | lambda = ${r.design.lambda}, L = ${r.design.L}; escalate after **${k}** consecutive out-of-control readings; inferred severity 0.7 |
| Transport forecast | 1D advection-dispersion, Taylor-dispersion closed form; Gaussian-CDF arrival probability; a sensitivity band on the ETA | Per-river mean velocity (placeholder, e.g. 0.36 m/s Mondego, 1.0 m/s large rivers) and a flat dispersion coefficient; band assumes velocity log-sd 0.5 |
| Exposure and card logic | Deterministic rules producing FHIR R4 \`RiskAssessment\` resources and CDS Hooks cards | 2 km station-proximity radius |

Version 0.1.0 (repository \`oah-mondego\`, shown in the interface as "OAH River Watch"). Developed for an EU / IEEE-style hackathon. No licence is declared.

## Intended use

- **Primary:** demonstrate, end to end, how a river-monitoring signal could become a clinician-facing decision-support card, using open standards (FHIR R4, CDS Hooks).
- **Primary users:** hackathon judges, researchers, and engineers exploring the pipeline.
- **Out of scope -- do not use for:** any clinical decision; excluding a diagnosis; delaying or withholding treatment; an exposure determination; regulatory or compliance reporting; real-world water-quality management. The full statement, including what regulation would apply if it were productised, is SAFETY_CASE.md section 1.

## Factors

- **Environmental:** river (7 modelled, ${stationsText} in 13 EU member states), reach length and velocity, flow regime (not modelled), season (not modelled), and event type -- the detector sees only events that move turbidity.
- **Data properties the detector is sensitive to:** independence of readings, noise level relative to the assumed baseline, distribution shape, and the sampling interval (assumed ${ASSUMED_SAMPLING_MINUTES} minutes for calendar-time conversions).
- **Population factors.** No patient attribute is used except a recorded address. That is itself the fairness-relevant factor: **people without a recorded, geocodable address, and people who live outside the 2 km radius of a monitored station, are systematically not covered**, however exposed they may be. Coverage follows where stations exist, which is not necessarily where risk or vulnerability is highest. No demographic breakdown of performance was possible or attempted.

## Metrics

Standard statistical-process-control metrics, chosen because there are no labelled events to compute classification metrics against:

- **ARL0** (readings between false alarms) and **ARL1** (readings to detect a shift of a given size).
- **False-escalation interval** for the escalation rule, per station and network-wide.
- **Sensitivity band** on the peak ETA (assumed, not calibrated).
- **Numerical-solution agreement** of the closed-form transport model with a direct finite-difference solution (peak time within 10%, spread within 15%).

No sensitivity, specificity, AUROC or calibration curve is reported: none can be computed without ground-truth incidents.

## Evaluation data

**Simulated, standardised noise** with fixed seeds (seed ${r.config.seed}): independent Gaussian (the design assumption), Gaussian with the standard deviation mis-stated, AR(1) autocorrelated, and right-skewed lognormal. The transport model is checked against a numerical PDE solution, not against field measurements. **No real river data, sensor data or patient data were used.**

## Training data

**None.** Nothing is learned. The baseline (15 NTU, sd 3 NTU) and the event shift (+45 NTU) are documented illustrative constants (\`src/analytics/telemetryStream.ts\`); river velocities are placeholders except where a source is named in METHODS.md.

## Quantitative analyses

Full tables and method in EVALUATION.md. Headlines (simulation only):

- **Correct implementation:** Markov-chain and Monte Carlo agree; production-class ARL0 = ${one(r.theory.mcProduction.mean)} readings.
- **Detection speed:** mean readings to detect a 1-sigma shift: EWMA ${one(at(1).ewma.mean)}, CUSUM ${one(at(1).cusum.mean)}, Shewhart ${one(at(1).shewhartMean)} (all at equal false-alarm rate). A 15-sigma shift -- the demo's injected event -- is caught on the first reading by all three.
- **Escalation rule (k = ${k}):** about ${int(shipped.falseEscalation.mean)} readings between false escalations per station under ideal assumptions; escalates a large event after ${one(shipped.delays.find((d) => d.shift === 15)!.summary.mean)} readings and a subtle 1-sigma shift after ${one(shipped.delays.find((d) => d.shift === 1)!.summary.mean)}.
- **Fragility:** that interval falls to about ${int(scenario("True sd 1.5x").escalationArl!.mean)} readings if the true noise is 1.5x the assumed value, and to about ${int(scenario("Autocorrelated, phi = 0.9").escalationArl!.mean)} readings under strong autocorrelation (phi = 0.9).
- **Baseline estimation:** a chart built from ${r.phaseOne[0]!.n} readings false-alarms within 50 readings ${(r.phaseOne[0]!.earlyFalseAlarmShare * 100).toFixed(0)}% of the time versus ${(r.phaseOne.at(-1)!.earlyFalseAlarmShare * 100).toFixed(0)}% at ${r.phaseOne.at(-1)!.n}.

## Ethical considerations

- **No personal data was used to build or evaluate anything.** In operation, a patient's address (health-related context) is processed per request; it is not logged or stored, and feedback comments are never stored (SAFETY_CASE.md H8). No DPIA or legal basis exists; none would be needed for the prototype as run, all would be before real use.
- **Risk of over-treatment:** an alert inferred from a turbidity trend must not drive therapy. Such alerts are shown at reduced urgency, labelled unconfirmed, with no empiric-therapy directive (SAFETY_CASE.md H2).
- **Risk of false reassurance:** no alert does not mean no exposure (H4).
- **Human oversight:** the software recommends; a clinician decides. Nothing acts autonomously on a patient.
- **Equity:** coverage and address-dependence (see Factors) can leave some populations unserved.
- **Transparency:** every figure in the interface is tagged verified or illustrative; nothing is presented as a measurement that is not one.

## Caveats and recommendations

1. Treat every number as illustrative. Velocity, dispersion, the baseline and the event size are placeholders.
2. Before using real telemetry, pass it through \`assessBaseline()\` (at least 200 readings, bounded autocorrelation) and **re-run the evaluation on that feed's actual behaviour**; the false-alarm interval above does not transfer to real data (EVALUATION.md section 4).
3. The chart is turbidity-only and mean-shift-only; it cannot see events without a turbidity signature. Do not use it as the sole safeguard for any hazard.
4. The two-sided chart also alarms on abnormally low turbidity, wasting false-alarm budget for this use; a one-sided variant is a candidate change, not made.
5. The sensitivity band is an assumption, not a calibrated interval.
6. This detector's own AI Act status (outside the "AI system" definition, section 2.2) is unchanged, but the project as a whole now has a component that IS a trained ML model -- see the citizen-report triage classifier's own model card below, a separate model with its own separate AI Act read.
7. Monitor the override rate once cards are shown to real clinicians (\`GET /monitoring/feedback\`), and treat a high sustained rate as a defect.

## Appendix: datasheet for the synthetic telemetry

Format after Gebru et al., *Datasheets for Datasets* (Communications of the ACM 64(12):86-92, 2021).

- **Motivation.** Give the detector something to detect without real sensors, so the pipeline can be demonstrated. Not created to represent any real river.
- **Composition.** A stream of one number per station per tick: turbidity in NTU, Gaussian noise (mean 15, sd 3) clipped at zero and rounded to 0.1. An injected event adds +45 NTU from the next tick. ${stationsText}. No personal or sensitive data.
- **Collection.** Generated on demand (Box-Muller transform over \`Math.random\`); reproducible when the server is started with \`OAH_SEED\`. No human subjects, no scraping.
- **Preprocessing.** None beyond clipping and rounding.
- **Uses.** Demonstrating and unit-testing the detector. **Not** suitable for estimating real-world detection performance.
- **Distribution and maintenance.** Not distributed as a dataset; it is produced by \`src/analytics/telemetryStream.ts\`. Maintained with the repository.
`;
}

/** A minimal shape of src/citizen/model.json -- just what this renderer reads. */
export interface CitizenModelData {
  seed: number;
  featureNames: readonly string[];
  weights: number[];
  bias: number;
  trainedOn: { n: number; heldOutN: number };
  metrics: { train: { loss: number; accuracy: number }; test: { loss: number; accuracy: number }; majorityClassBaselineAccuracy: number };
}

/** A second, separate model card for the citizen-report triage classifier
 * -- a genuinely different model (trained ML, not the EWMA/physics/rules
 * components above) with its own separate intended use, data and AI Act
 * read (SAFETY_CASE.md section 2.2). Appended to the same MODEL_CARD.md
 * rather than a new file so both models a reader might ask "is this AI?"
 * about are answered in one place. */
export function renderCitizenModelCardSection(m: CitizenModelData): string {
  const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
  const weighted = m.featureNames.map((name, i) => ({ name, weight: m.weights[i]! })).sort((a, b) => b.weight - a.weight);

  return `
---

# Model card: citizen-report triage classifier

A second, separate model from the detector above -- included here so both
models this project ships get an equally honest card, not just the one
that came first.

## Model details

A **logistic regression**, weights fit by batch gradient descent on
L2-regularized binary cross-entropy loss (\`src/citizen/logisticRegression.ts\`,
implemented from scratch, no ML library dependency -- the point is that its
~60 lines are directly inspectable). Trained by
\`scripts/trainCitizenClassifier.ts\`; weights committed at
\`src/citizen/model.json\` (seed ${m.seed}, fully reproducible).

Unlike the EWMA detector, network transport model and exposure/card logic
documented above -- all fixed-form, human-parameterised, and assessed as
outside the EU AI Act's "AI system" definition (SAFETY_CASE.md section
2.2) -- **this is a trained machine-learning model**, and on our reading
**likely does qualify** as an AI system under the Act. That is a real,
substantive difference between the two models in this one project, not a
technicality.

## Intended use

Score a citizen's structured water/habitat observation (clarity 1-5,
unusual odor, dead wildlife, discoloration, foam -- modelled on the real
OneAquaHealth Citizen Science App's own observation categories) for
whether a **human water-authority reviewer** should look at it. It **never**
confirms an exposure itself -- see \`src/citizen/observations.ts\` and
SAFETY_CASE.md hazard H13. Not intended for any other input shape, any
other decision, or any automated action.

## Factors

Five binary/ordinal features, listed here by their learned weight (largest
first -- every one is positive, i.e. every modelled risk factor pushes
toward "recommend review", which matches the documented labelling rule
it was trained to approximate):

${weighted.map((w, i) => `${i + 1}. **${w.name}** (weight ${w.weight.toFixed(3)})`).join("\n")}

Bias term: ${m.bias.toFixed(3)} (negative -- a report with no red flags defaults toward "no concern").

## Metrics

Held-out accuracy and loss, and a majority-class baseline -- a classifier
that just always predicted the more common class would already score
${pct(m.metrics.majorityClassBaselineAccuracy)}, so accuracy alone would be
misleading without it printed alongside.

| | Train (n=${m.trainedOn.n}) | Held-out test (n=${m.trainedOn.heldOutN}) |
|---|---|---|
| Accuracy | ${pct(m.metrics.train.accuracy)} | ${pct(m.metrics.test.accuracy)} |
| Cross-entropy loss | ${m.metrics.train.loss.toFixed(3)} | ${m.metrics.test.loss.toFixed(3)} |
| Majority-class baseline | -- | ${pct(m.metrics.majorityClassBaselineAccuracy)} |

Every prediction also returns a full, literal explanation (\`explainLogit\`):
each feature's contribution to the logit, which sum exactly to the
model's output -- not a post-hoc approximation of a black box, because
there is no black box here to approximate.

## Evaluation data / Training data

**Entirely synthetic**, generated and labelled by a documented rule
(\`src/citizen/trainingData.ts\`'s \`ruleBasedLabel\`, with 5% label noise) --
**not** real citizen submissions, none of which exist in or were used by
this project. The labelling rule is this project's own judgement call
about which combinations plausibly warrant review, disclosed as a design
choice, not derived from any published water-quality guidance.

## Ethical considerations

- **Human-in-the-loop by construction** (SAFETY_CASE.md H13.1): the
  highest-probability output this model can produce still only creates a
  pending record for a human to review, never a confirmed exposure.
- **Never evaluated on a real citizen report.** Held-out accuracy above is
  against more synthetic data drawn from the same generator -- it says the
  model learned the synthetic rule, not that it will perform well on real
  human submissions, which may differ from the synthetic distribution in
  ways this evaluation cannot see.
- **No submitter identity or abuse defence** (H13.5): the model scores
  whatever it is given; nothing here detects a coordinated false-reporting
  campaign.

## Caveats and recommendations

1. Do not treat "held-out accuracy 90%" as real-world accuracy -- it is
   synthetic-data accuracy, a check that training worked, not a
   real-world performance claim.
2. Before any real deployment, get real, labelled citizen reports (even a
   small pilot set) and re-evaluate on those specifically.
3. The review threshold (0.35, not the model's own 0.5 decision boundary)
   is a deliberate choice to favour false positives over false negatives
   -- re-examine it once real-world costs of each error type are known.
4. Revisit the AI Act qualification above with a qualified person before
   any real use, alongside the MDR question in SAFETY_CASE.md section 2.1.
`;
}

