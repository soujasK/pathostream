/**
 * Renders EVALUATION.md from an EvaluationResults. Every number in the
 * document is computed from the data; only the framing prose is static, so
 * the document cannot drift from the results it describes.
 */

import {
  ASSUMED_SAMPLING_MINUTES,
  MIN_RELIABLE_CYCLES,
  requiredPerStationArl,
  smallestPersistenceMeetingTarget,
  TARGET_FALSE_ESCALATIONS_PER_30_DAYS,
  type EvaluationResults,
} from "./experiments.js";
import type { RunLengthSummary } from "./runLength.js";

const int = (x: number) => Math.round(x).toLocaleString("en-US");
const one = (x: number) => x.toFixed(1);
const pm = (s: RunLengthSummary) => `${one(s.mean)} ± ${one(1.96 * s.se)}`;

/** Ticks -> a readable duration at the assumed sampling interval. */
function hoursText(ticks: number, minutesPerTick: number): string {
  const hours = (ticks * minutesPerTick) / 60;
  if (hours < 1) return `${(hours * 60).toFixed(0)} min`;
  if (hours < 48) return `${hours.toFixed(1)} h`;
  return `${(hours / 24).toFixed(1)} days`;
}

function table(headers: string[], rows: string[][]): string {
  const line = (cells: string[]) => `| ${cells.join(" | ")} |`;
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

export function renderEvaluationMarkdown(r: EvaluationResults & { generatedWith?: { node: string; seed: number } }): string {
  const { design, theory, delay, persistence, robustness, phaseOne, gate, networkStations: stations } = r;
  const k = design.escalationThresholdTicks;
  const required = requiredPerStationArl(stations);
  const smallestK = smallestPersistenceMeetingTarget(persistence, stations);
  const chosen = persistence.find((p) => p.k === k);
  const baseline = robustness[0]!;
  const markovLimit = theory.markovArl0.at(-1)!.arl0;

  const out: string[] = [];
  out.push(`# Evaluation of the early-warning detector

> **Scope.** This evaluates the *statistical detector* — an EWMA control chart (λ = ${design.lambda}, L = ${design.L}) followed by a rule that escalates after **${k}** consecutive out-of-control readings — on **simulated, standardised data**. It shows how the detector behaves when its assumptions hold and how it degrades when they do not. It says **nothing about performance on real rivers**: no real sensor data and no labelled contamination incidents were used, and none exist in this repository. Nothing here is a clinical validation.

Generated by \`npm run evaluate\` from \`src/evaluation/\` (do not edit by hand). Seed \`${r.config.seed}\`${r.generatedWith ? `, Node ${r.generatedWith.node}` : ""}; same seed and Node major version reproduce every number. The EWMA runs through the **production class** (\`src/analytics/ewma.ts\`) and the design constants come from \`src/analytics/detectorConfig.ts\`, so this document cannot describe a different detector from the one that ships. All data are standardised (in-control mean 0, sd 1); "ticks" are sampling intervals.

Terms: **ARL0** = average number of readings between *false* alarms (bigger is better). **ARL1** = average readings to detect a real shift of a given size in σ (smaller is better). ± is a 95% interval on the simulated mean.
`);

  out.push(`## 1. Is the detector implemented correctly?

Two independent methods should agree: a Markov-chain calculation (introduced for CUSUM charts by Brook & Evans 1972, *Biometrika* 59(3):539-549, and applied to EWMA by Lucas & Saccucci 1990, *Technometrics* 32(1):1-12) and Monte Carlo.

${table(
  ["Method", "ARL0"],
  [
    ["Shewhart 3σ, closed form (sanity anchor)", theory.shewhartArl0Exact.toFixed(2)],
    ...theory.markovArl0.map((m) => [`Markov chain, ${m.cells} cells (asymptotic limits)`, m.arl0.toFixed(2)]),
    ["Monte Carlo, asymptotic limits", pm(theory.mcAsymptotic)],
    ["**Monte Carlo, production class (exact time-varying limits)**", `**${pm(theory.mcProduction)}**`],
  ],
)}

The Markov chain converges to ${markovLimit.toFixed(1)} as cells increase and the asymptotic-limit simulation (${pm(theory.mcAsymptotic)}) agrees with it. The production class, whose limits are tighter for the first few readings after a (re)start, sits ${((1 - theory.mcProduction.mean / markovLimit) * 100).toFixed(1)}% lower — the expected direction, and small (simulation noise alone is about ±1%). (The solver is also checked in \`test/evaluation.test.ts\` against the exact Shewhart value: with λ = 1 the Markov chain must return 370.398 and does.)
`);

  out.push(`## 2. How fast does it detect, compared with standard alternatives?

Both baselines are tuned to the **same false-alarm rate** as the shipped EWMA (ARL0 ≈ ${one(delay.targetArl0)}), so the comparison is fair: two-sided CUSUM (Page 1954, *Biometrika* 41:100-115) with k = ${delay.cusum.k}, h = ${delay.cusum.h.toFixed(2)} found by calibration, and a Shewhart individuals chart with limits ±${delay.shewhartK.toFixed(2)}σ. Mean readings to detect (95% p95 in brackets):

${table(
  ["Shift (σ)", "EWMA (shipped)", "CUSUM", "Shewhart"],
  delay.rows.map((row) => [
    String(row.shift),
    `${pm(row.ewma)} (${int(row.ewma.p95)})`,
    `${pm(row.cusum)} (${int(row.cusum.p95)})`,
    one(row.shewhartMean),
  ]),
)}

**Reading it.** EWMA and CUSUM both beat a single-reading threshold decisively for shifts up to about 2σ (the Shewhart chart needs ${int(delay.rows.find((x) => x.shift === 1)!.shewhartMean)} readings on average to see a 1σ shift; EWMA needs ${one(delay.rows.find((x) => x.shift === 1)!.ewma.mean)}). CUSUM is faster than EWMA at 0.5σ; EWMA is faster from 1.5σ upward. **At the demo's injected event (+45 NTU on a 3 NTU baseline = 15σ) all three detect on the very first reading**, so the live demo does not exercise the detector's small-shift sensitivity — the table above is where that evidence lives.
`);

  const rows3 = persistence.map((p) => {
    const e = p.falseEscalation;
    const reliable = e.n >= MIN_RELIABLE_CYCLES;
    const delayFor = (s: number) => one(p.delays.find((d) => d.shift === s)!.summary.mean);
    return [
      p.k === k ? `**${p.k}** (shipped)` : String(p.k),
      reliable ? `${int(e.mean)} (${int(e.mean - 1.96 * e.se)}–${int(e.mean + 1.96 * e.se)})` : `not estimated (${e.n} completed cycle${e.n === 1 ? "" : "s"})`,
      reliable ? hoursText(e.mean / stations, ASSUMED_SAMPLING_MINUTES) : "—",
      delayFor(1),
      delayFor(2),
      delayFor(3),
      delayFor(15),
    ];
  });
  out.push(`## 3. The escalation rule (${k} consecutive out-of-control readings)

A single EWMA signal is not enough to auto-escalate a station: the rule requires **k consecutive** out-of-control readings. Longer persistence means fewer false escalations but slower detection. "False escalation" = the rule fires with no real shift; after each one the detector is reset (what an operator clearing the station does) and the next interval is measured. Estimated by a regenerative simulation of ${int(r.config.escalationTicks)} readings per k; an estimate needs at least ${MIN_RELIABLE_CYCLES} completed intervals to be reported (rarer events are truncated by the simulation horizon and would be biased low).

${table(
  [
    "k",
    "Mean readings between false escalations, per station (95% CI)",
    `Network-wide (${stations} stations) at ${ASSUMED_SAMPLING_MINUTES}-min sampling`,
    "Delay @1σ",
    "@2σ",
    "@3σ",
    "@15σ",
  ],
  rows3,
)}

**Design target (ours, not a standard).** At most ${TARGET_FALSE_ESCALATIONS_PER_30_DAYS} false auto-escalation per 30 days across all ${stations} stations, assuming ${ASSUMED_SAMPLING_MINUTES}-minute sampling (an assumption): that needs ≥ ${int(required)} readings between false escalations *per station*. ${
    smallestK === null
      ? "No tested k meets it with a trustworthy estimate."
      : `The smallest k meeting it, counting only the lower end of the 95% interval, is **k = ${smallestK}**${smallestK === k ? " — the value that ships" : ` — but the shipped value is ${k}, which this evidence does not support; re-derive it`}.`
  } Whether that target is acceptable is an operator's policy decision; the number exists so the threshold is derived from something explicit.

**The price of persistence.** Under this rule a large event is escalated after ${one(chosen!.delays.find((d) => d.shift === 15)!.summary.mean)} readings (vs 1.0 for the bare chart) and a subtle 1σ shift after ${one(chosen!.delays.find((d) => d.shift === 1)!.summary.mean)} (vs ${one(delay.rows.find((x) => x.shift === 1)!.ewma.mean)}). Subtle events therefore surface first as *unescalated* out-of-control signals on the Timeline, which is the intended behaviour, not a failure.
`);

  // The "assumptions hold" row is the same quantity as the shipped row of
  // §3, which used a 4x longer run; use that (tighter) estimate for it and
  // for every ratio so the two tables never disagree.
  const referenceEscalation = chosen!.falseEscalation;
  const robustRows = robustness.map((row) => {
    const e = row === baseline ? referenceEscalation : row.escalationArl!;
    const ratio = e.mean / referenceEscalation.mean;
    const reliable = e.n >= MIN_RELIABLE_CYCLES;
    return [
      row.scenario,
      pm(row.arl0),
      reliable ? int(e.mean) : `≥ ${int(e.mean)} (n=${e.n})`,
      reliable ? hoursText(e.mean / stations, ASSUMED_SAMPLING_MINUTES) : "—",
      row === baseline ? "1×" : `${ratio >= 0.1 ? ratio.toFixed(2) : ratio.toFixed(3)}×`,
    ];
  });
  const scenario = (prefix: string) => robustness.find((x) => x.scenario.startsWith(prefix))!;
  const sd125 = scenario("True sd 1.25x").escalationArl!;
  const phi09 = scenario("Autocorrelated, phi = 0.9").escalationArl!;
  out.push(`## 4. What breaks it

The detector assumes independent Gaussian readings with a known mean and standard deviation. Real sensor data violate all three. Each row changes one assumption and reports both the bare chart's ARL0 and the false-escalation interval of the shipped ${k}-reading rule:

${table(
  ["Scenario", "Bare-chart ARL0", `False escalation: readings/station`, `Network-wide at ${ASSUMED_SAMPLING_MINUTES}-min`, "vs assumptions holding"],
  robustRows,
)}

**This is the most important table in the document.** The ${k}-reading rule is very conservative *only while its assumptions hold*. If the true noise is 25% larger than assumed, false escalations become roughly ${Math.round(referenceEscalation.mean / sd125.mean)}× more frequent; with strong autocorrelation (φ = 0.9 — a value we have not measured on any real river, included because closely spaced readings of a slowly varying quantity can be strongly autocorrelated) the rule falsely escalates about every ${int(phi09.mean)} readings per station — unusable. The demo hides all of this because its synthetic telemetry satisfies the assumptions by construction. **Any real feed must pass the baseline gate in §5 first, and the escalation rule must be re-evaluated on that feed's actual behaviour before anyone relies on it.**
`);

  out.push(`## 5. Estimating the baseline from data

In deployment the mean and sd are *estimated* from a Phase-I window, not known. The same chart built from n readings, then run on fresh in-control data:

${table(
  ["Phase-I readings n", "Mean ARL0", "Median ARL0", "5th percentile", "Signals within first 50 readings"],
  phaseOne.map((p) => [String(p.n), pm(p.arl0), int(p.arl0.median), int(p.arl0.p05), `${(p.earlyFalseAlarmShare * 100).toFixed(1)}%`]),
)}

With n = ${phaseOne[0]!.n} the mean ARL0 looks *better* than nominal, but the median is far worse and ${(phaseOne[0]!.earlyFalseAlarmShare * 100).toFixed(0)}% of charts false-alarm within 50 readings (the average is dominated by a few charts whose σ was over-estimated; most are too tight). The early-false-alarm share settles near its n = ${phaseOne.at(-1)!.n} value (${(phaseOne.at(-1)!.earlyFalseAlarmShare * 100).toFixed(1)}%) only for n in the hundreds. \`assessBaseline()\` (src/analytics/baseline.ts) therefore requires n ≥ 200 and a lag-1 autocorrelation inside a limit. How often its autocorrelation check rejects a baseline:

${table(
  ["Window n", "True φ", "Share rejected"],
  gate.map((g) => [String(g.n), String(g.phi), `${(g.rejectShare * 100).toFixed(1)}%`]),
)}

(φ = 0 rows are the gate's false-reject rate on genuinely independent data; the rest are its power.) It is a **coarse screen, not a guarantee**: a φ = 0.1 baseline — which already cuts the bare chart's ARL0 to ${one(scenario("Autocorrelated, phi = 0.1").arl0.mean)} — is rejected only ${((gate.find((g) => g.n === 200 && g.phi === 0.1)?.rejectShare ?? 0) * 100).toFixed(0)}% of the time at n = 200. The gate is **not** wired into the demo, whose telemetry is synthetic with a known baseline; it is the prerequisite for any real feed.
`);

  out.push(`## 6. What this does not show

- **No real data.** Everything is simulated on standardised Gaussian/AR(1)/lognormal noise. No claim about any real river, sensor, or incident follows.
- **No sensitivity or specificity for real events.** ARL is a property of the chart under an assumed process, not a labelled-event detection rate. There is no ground-truth incident set here to compute recall or precision against.
- **Turbidity only, mean-shift only.** The chart detects a sustained upward or downward shift in one variable. It cannot see an event with no turbidity signature — for example the 2022 Oder die-off was an algal bloom, which a turbidity chart would not have caught.
- **Assumed sampling interval** (${ASSUMED_SAMPLING_MINUTES} min) and design target are our assumptions, used only to translate ticks into calendar time.
- **Two-sided chart.** It also alarms on abnormally *low* turbidity; that is wasted false-alarm budget for a contamination use case and a candidate change, not made here.
- **Escalation-rule estimates** use a regenerative simulation and discard the final incomplete interval; intervals with fewer than ${MIN_RELIABLE_CYCLES} completed cycles are not reported.
- **Autocorrelated scenarios** re-use the noise stream across resets, so the regenerative interval estimates there are approximate.

## 7. Decisions taken from these results

1. **Keep k = ${k}**${smallestK === k ? ` — it is the smallest persistence meeting the stated design target with a trustworthy estimate` : ""}. It is a documented, evidence-backed operating point, *conditional on §4's assumptions*.
2. **A statistically-inferred flag is never presented to a clinician as a confirmed exposure**: the CDS Hooks card is downgraded to \`warning\`, labelled unconfirmed, and carries no empiric-therapy directive or order suggestion (SAFETY_CASE.md, hazard H2). This follows directly from §4: the alarm is only as trustworthy as its baseline.
3. **Baseline gate required before any real feed** (§5).
4. **Expect occasional spurious escalations in a long-running demo**: at the demo's ${1.2}-second tick, ${stations} stations and ~${int(chosen!.falseEscalation.mean)} readings per false escalation, the network-wide interval is about ${hoursText(chosen!.falseEscalation.mean / stations, 1.2 / 60)} of continuous ticking. That is the measured false-alarm rate, not a bug.
`);
  return out.join("\n");
}
